function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".next") continue;
      walk(full, out);
      continue;
    }
    if (!exts.has(path.extname(entry.name))) continue;
    out.push(full);
  }
  return out;
}

function applyReplacements(text) {
  let next = text;
  let hits = 0;
  for (const [pattern, replacement] of replacements) {
    next = next.replace(pattern, () => {
      hits += 1;
      return replacement;
    });
  }
  return { text: next, hits };
}

function escapeForNode(node, text, source) {
  if (ts.isStringLiteral(node)) {
    const quote = source[node.getStart()] || "\"";
    let value = text.replace(/\\/g, "\\\\");
    if (quote === "'") value = value.replace(/'/g, "\\'");
    if (quote === "\"") value = value.replace(/"/g, "\\\"");
    value = value.replace(/\r/g, "\\r").replace(/\n/g, "\\n");
    return value;
  }
  if (ts.isNoSubstitutionTemplateLiteral(node)) {
    return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  }
  return text;
}

let changedFiles = 0;
let totalHits = 0;

for (const file of roots.flatMap((root) => walk(root))) {
  const source = fs.readFileSync(file, "utf8");
  const scriptKind = file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, scriptKind);
  const edits = [];

  function visit(node) {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      const result = applyReplacements(node.text);
      if (result.hits > 0 && result.text !== node.text) {
        edits.push({
          start: node.getStart(sourceFile) + 1,
          end: node.getEnd() - 1,
          text: escapeForNode(node, result.text, source),
          hits: result.hits,
        });
      }
    }
    ts.forEachChild(node, visit);
  }

  visit(sourceFile);

  if (!edits.length) continue;

  let next = source;
  for (const edit of edits.sort((a, b) => b.start - a.start)) {
    next = next.slice(0, edit.start) + edit.text + next.slice(edit.end);
  }

  if (next !== source) {
    fs.writeFileSync(file, next, "utf8");
    changedFiles += 1;
    totalHits += edits.reduce((sum, edit) => sum + edit.hits, 0);
  }
}

console.log(`changed files: ${changedFiles}`);
console.log(`total replacements: ${totalHits}`);
