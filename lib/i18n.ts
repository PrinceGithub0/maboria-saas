export const SUPPORTED_LANGUAGES = ["en", "fr", "de", "es", "pt"] as const;

export type Language = (typeof SUPPORTED_LANGUAGES)[number];

export const DEFAULT_LANGUAGE: Language = "en";

export type CompleteLocalizedText = Record<Language, string>;

export type LocalizedText = {
  en: string;
  fr?: string;
  de?: string;
  es?: string;
  pt?: string;
};

export function defineLocalizedText<T extends CompleteLocalizedText>(text: T): T {
  return text;
}

export function resolveLocalizedText(text: LocalizedText): CompleteLocalizedText {
  const key = String(text.en || "").trim();
  const fallback = key ? FALLBACK_TRANSLATIONS[key] : undefined;
  const en = text.en || fallback?.en || "";
  const fr = text.fr || fallback?.fr || en;
  const de = text.de || fallback?.de || en || fr;
  const es = text.es || fallback?.es || en || fr;
  const pt = text.pt || fallback?.pt || en || fr;
  return { en, fr, de, es, pt };
}

