export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && SUPPORTED_LANGUAGES.includes(value as Language);
}

export function normalizeLanguage(value: unknown, fallback: Language = DEFAULT_LANGUAGE): Language {
  return isLanguage(value) ? value : fallback;
}

function getFallbackTranslation(text: LocalizedText, language: Language): string | undefined {
  const key = String(text.en || "").trim();
  if (!key) return undefined;
  const fallback = FALLBACK_TRANSLATIONS[key];
  if (!fallback) return undefined;
  return fallback[language] || undefined;
}

export function getLocalizedText(text: LocalizedText, language: Language): string {
  return (
    text[language] ||
    getFallbackTranslation(text, language) ||
    text.en ||
    text.fr ||
    text.de ||
    text.es ||
    text.pt ||
    ""
  );
}

export function getLanguageDisplayName(language: Language, uiLanguage: Language): string {
  return getLocalizedText(LANGUAGE_LABELS[language], uiLanguage);
}

export function getLanguageShortCode(language: Language): string {
  return language.toUpperCase();
}

